/** 탭에 나오는 것 전부. */
export const FIND_TABS = [...FIND_STRUCTS, FIND_RACE];

export function findStructById(id) {
    return FIND_TABS.find((s) => s.id === id) || null;
}

export function findStructsOfGroup(groupId) {
    return FIND_TABS.filter((s) => s.group === groupId);
}

export function findGroupById(id) {
    return FIND_GROUPS.find((g) => g.id === id) || null;
}

export function findGroupsInUse() {
    return FIND_GROUPS.filter((g) => findStructsOfGroup(g.id).length > 0);
}

/** 지금 고른 구조와 담는 방식으로 무엇을 쓸지 고른다. */
export function findPlanOf(struct, implId) {
    if (!struct.impls) return {view: struct.view, ops: struct.ops, impl: null};
    const impl = struct.impls.find((i) => i.id === implId) || struct.impls[0];
    return {view: struct.view, ops: impl.ops, impl};
}
