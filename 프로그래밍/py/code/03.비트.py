a = 12          # 이진수로 1100
b = 10          # 이진수로 1010

print(a & b)    # 8    1000   둘 다 1인 자리만 1
print(a | b)    # 14   1110   하나라도 1이면 1
print(a ^ b)    # 6    0110   서로 다르면 1
print(a << 1)   # 24   11000  왼쪽으로 한 칸 = 2배
print(a >> 1)   # 6    110    오른쪽으로 한 칸 = 2로 나눈 몫
