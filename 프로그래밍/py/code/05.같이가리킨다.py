a = [1, 2, 3]
b = a                  # «같은 리스트»에 이름을 하나 더 붙인 것이다
b.append(4)
print(a)               # [1, 2, 3, 4]   a도 함께 바뀐다

c = a[:]               # 통째로 잘라 «새 리스트»를 만든다
c.append(5)
print(a)               # [1, 2, 3, 4]   이번에는 그대로다
print(c)               # [1, 2, 3, 4, 5]
