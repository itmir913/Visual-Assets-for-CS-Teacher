# 연도와 월을 한 줄에 공백으로 띄어 입력받는다
year, month = map(int, input().split())

# 1월부터 12월까지의 말일. 2월은 일단 평년 값으로 둔다
days = [31, 28, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31]

# 윤년이면 2월만 29로 바꾼다. 출력하기 전에 바꿔야 한다
if (year % 400 == 0) or (year % 4 == 0 and year % 100 != 0):
    days[1] = 29

# 1월이 0번 자리이므로 1을 뺀다
print(days[month - 1])
